def find_callouts(text):
    """Yield (family, dims, raw) for every AISC-looking designation in text,
    plus ("JOIST", [designation], raw) for SJI joist designations."""
    t = clean(text)
    for m in CALLOUT.finditer(t):
        fam = m.group(1).upper()
        dims = [d.strip() for d in m.groups()[1:] if d]
        yield fam, dims, m.group(0)
    for m in JOIST.finditer(t):
        series = m.group(2) or m.group(4)
        section = m.group(3) if m.group(2) else m.group(5)
        desig = (m.group(1) + series + (section or "")).upper()
        yield "JOIST", [desig], m.group(0)


def resolve(fam, dims):
    """Return (key, confidence, note). key is the estimator's table key or None."""
    if fam == "JOIST":
        desig = dims[0].upper()
        if desig in JOIST_WEIGHTS:
            return desig, 1.0, ""
        return desig, 0.9, "joist weight from supplier (special / not in SJI approx table)"
    if fam == "PL":
        return None, 0.0, "plate callout (plates are not auto-counted)"
    if fam == "HP":
        return None, 0.0, "HP shape not in the estimator's shape table"
    db()
    cand = list(dims)
    if fam in ("L", "HSS") and len(cand) == 3:
        cand = [_to_fraction(c) for c in cand]
    key = norm(fam + "x".join(cand))
    if key in _INDEX:
        return _INDEX[key], 1.0, ""
    key2 = re.sub(r"\.0+(?=X|$)", "", key)          # "W8x21.0"
    if key2 in _INDEX:
        return _INDEX[key2], 0.95, "trailing .0 dropped"
    prefix = norm(fam + cand[0]) + "X"
    pool = [k for k in _INDEX if k.startswith(prefix)]
    close = difflib.get_close_matches(key, pool, n=2, cutoff=0.85)
    if len(close) == 1:
        return _INDEX[close[0]], 0.7, f"fuzzy from {fam} {' x '.join(dims)}"
    if len(close) > 1:
        return None, 0.0, "ambiguous: " + ", ".join(_INDEX[c] for c in close)
    return None, 0.0, "no such size in the estimator's shape table"


def weight(key):
    if key in JOIST_WEIGHTS:
        return JOIST_WEIGHTS[key]
    return db().get(key, {}).get("weight")


def category(key):
    if key in JOIST_WEIGHTS or JOIST.fullmatch(key or ""):
        return "Joist"
    return db().get(key, {}).get("category")


def all_weights():
    """{key: lb/ft} for every shape the sidecar can name (AISC table + joists)."""
    w = {k: v["weight"] for k, v in db().items()}
    w.update(JOIST_WEIGHTS)
    return w
