"""AISC callout matching against the estimator's own shape table
(sidecar/aisc-shapes.json, generated by scripts/export-aisc-shapes.mjs).

find_callouts(text) yields regex hits; resolve(fam, dims) turns a hit into the
estimator's key ('W8x21', 'HSS6x6x3/8') with a confidence, or None."""
import difflib
import json
import re
from fractions import Fraction
from pathlib import Path

_DB = None
_INDEX = None


def load_db(path=None):
    global _DB, _INDEX
    path = Path(path or Path(__file__).with_name("aisc-shapes.json"))
    _DB = json.loads(path.read_text())
    _INDEX = {norm(k): k for k in _DB}
    return _DB


def db():
    return _DB if _DB is not None else load_db()


_NUM = r"[0-9]+(?:\s*-\s*[0-9]+/[0-9]+|\s+[0-9]+/[0-9]+|/[0-9]+)?(?:\.[0-9]+)?|\.[0-9]+"
_SEP = r"\s*[xX\u00d7]\s*"
CALLOUT = re.compile(
    rf"(?<![A-Z0-9])(HSS|MC|WT|HP|PIPE|PL|W|C|L)\s*({_NUM}){_SEP}({_NUM})(?:{_SEP}({_NUM}))?(?![0-9/])",
    re.I,
)
_VULGAR = {"\u00bc": "1/4", "\u00bd": "1/2", "\u00be": "3/4", "\u215b": "1/8", "\u215c": "3/8",
           "\u215d": "5/8", "\u215e": "7/8", "\u2153": "1/3", "\u2154": "2/3"}


def clean(text):
    for k, v in _VULGAR.items():
        text = text.replace(k, " " + v)
    return text.replace("\u00d7", "x").replace("\u2013", "-").replace("\u2014", "-")


def norm(s):
    """Comparison form: upper, no whitespace."""
    return re.sub(r"\s+", "", clean(s)).upper()


def _to_fraction(tok):
    """'0.375' -> '3/8'; '3/8' stays; '1 1/2' -> '1-1/2'; '21' stays."""
    tok = tok.strip()
    if re.fullmatch(r"[0-9]*\.[0-9]+", tok):
        f = Fraction(tok).limit_denominator(16)
        if f.denominator == 1:
            return str(f.numerator)
        whole, rem = divmod(f.numerator, f.denominator)
        return f"{whole}-{rem}/{f.denominator}" if whole else f"{rem}/{f.denominator}"
    return re.sub(r"\s*-\s*|\s+", "-", tok)


# Open-web steel joists (SJI): depth + series + section, e.g. 20LH04, 24K4,
